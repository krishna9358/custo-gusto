/* Regenerates schema_homepage.html from lib/homeSchema.ts, so the standalone
   snippet is always byte-for-byte the graph the homepage renders.
   Usage: npm run schema:homepage */
const fs = require('fs');
const os = require('os');
const path = require('path');

const repo = path.resolve(__dirname, '..');
const ts = require('typescript');
const outDir = fs.mkdtempSync(path.join(os.tmpdir(), 'cg-schema-'));

const files = { seo: 'lib/seo.ts', seoPages: 'data/seoPages.ts', homeSchema: 'lib/homeSchema.ts' };
for (const [name, rel] of Object.entries(files)) {
  const src = fs
    .readFileSync(path.join(repo, rel), 'utf8')
    .replace(/'@\/lib\/seo'/g, "'./seo'")
    .replace(/'@\/data\/seoPages'/g, "'./seoPages'");
  const out = ts.transpileModule(src, {
    compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2019 },
  }).outputText;
  fs.writeFileSync(path.join(outDir, `${name}.js`), out);
}

const { HOME_SCHEMA } = require(path.join(outDir, 'homeSchema.js'));
const json = JSON.stringify(HOME_SCHEMA, null, 2);
const html = `<!--
  Custo Gusto homepage structured data (JSON-LD): Organization, WebSite and WebPage.
  The live site renders this same graph on "/" from lib/homeSchema.ts (via components/JsonLd).
  Do not edit this file by hand: edit lib/homeSchema.ts and run \`npm run schema:homepage\`.
-->
<script type="application/ld+json">
${json}
</script>
`;
fs.writeFileSync(path.join(repo, 'schema_homepage.html'), html);
fs.rmSync(outDir, { recursive: true, force: true });
console.log(`schema_homepage.html written (${HOME_SCHEMA['@graph'].length} nodes)`);
